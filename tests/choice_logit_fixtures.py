"""Synthetic mice whose choices follow a known logit, for the choice-logit extension tests."""

import numpy as np
import pandas as pd

from src.pipelines.choice_logit_values import SIMULATED_PORTS


def _softmax(utility: np.ndarray) -> np.ndarray:
    weights = np.exp(utility - utility.max())
    return weights / weights.sum()


def simulate_logit_trials(
    mouse: str,
    seed: int,
    *,
    pulse_weight: float = 0.0,
    binary_weight: float = 0.0,
    choice_weight: float = 0.0,
    tower_weights: dict | None = None,
    n_problems: int = 6,
    sessions_per_problem: int = 2,
    trials_per_session: int = 300,
) -> pd.DataFrame:
    """One mouse's drifting trial table, generated by a conditional logit on lag-1 history.

    The utility of an arm is ``pulse_weight * pulses received there on the previous trial +
    binary_weight * 1[those pulses > 0] + choice_weight * 1[chosen on the previous trial] +
    tower_weights[port]``. Every arm offers 0-4 pulses at random on every trial, so pulses and
    rewarded-or-not are different regressors. Reward history carries across the sessions of a
    problem; choice history is cleared at a session start, as the design matrix does.

    Args:
        mouse (str): Mouse id.
        seed (int): Seed of the generator.
        pulse_weight (float): Logit per pulse received on the previous trial.
        binary_weight (float): Logit for a rewarded previous trial.
        choice_weight (float): Logit for repeating the previous choice.
        tower_weights (dict | None): ``{port: logit}``; unlisted ports have 0.
        n_problems (int): Problems; they cycle through the simulated tower triples.
        sessions_per_problem (int): Sessions per problem.
        trials_per_session (int): Trials per session.

    Returns:
        pd.DataFrame: The columns of ``drifting_trial_table`` that the logit reads.
    """
    rng = np.random.default_rng(seed)
    tower_weights = tower_weights or {}
    rows = []
    for k in range(n_problems):
        ports = sorted(SIMULATED_PORTS[k % len(SIMULATED_PORTS)])
        tower = np.array([tower_weights.get(p, 0.0) for p in ports])
        received = np.zeros(3)
        trial = 0
        for session in range(sessions_per_problem):
            previous = None
            for in_session in range(trials_per_session):
                utility = pulse_weight * received + binary_weight * (received > 0) + tower
                if previous is not None:
                    utility[previous] += choice_weight
                magnitudes = rng.integers(0, 5, size=3)
                chosen = int(rng.choice(3, p=_softmax(utility)))
                received = np.zeros(3)
                received[chosen] = magnitudes[chosen]
                previous = chosen
                rows.append(
                    dict(
                        mouse=mouse,
                        problem=k + 1,
                        session=f"s{session}",
                        session_index=session,
                        trial=trial,
                        trial_in_session=in_session,
                        choice=ports[chosen],
                        magnitudes=dict(zip(ports, (int(m) for m in magnitudes), strict=True)),
                        reward=int(magnitudes[chosen]),
                        initiation="B2",
                        block=None,
                        after_gap=False,
                    )
                )
                trial += 1
    return pd.DataFrame(rows)


def simulate_logit_cohort(n_mice: int, seed: int, **kwargs) -> pd.DataFrame:
    """Trial tables of *n_mice* mice (``m1``, ``m2``, ...) from :func:`simulate_logit_trials`."""
    return pd.concat(
        [simulate_logit_trials(f"m{i}", seed + i, **kwargs) for i in range(1, n_mice + 1)],
        ignore_index=True,
    )
