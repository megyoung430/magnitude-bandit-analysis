"""The heuristic-versus-value-learner comparison for one source of choices, and model recovery.

Steps, each a plain function:

1. **Compare** (:func:`analyze_comparison_source`): per mouse, the leave-one-problem-out
   comparison of WSLS (Magnitude), Heuristic+ and the Q-learner of
   :mod:`src.behavior_analysis.strategy_models`. Mice are independent: the work is parallel over
   mice and each mouse's result is cached, keyed on its trials, the settings and the source of
   the modules (:func:`code_version`). The choice logit's held-out nats per choice of the same
   mice are carried along as a descriptive reference; they include the segment starts, which the
   three models are not scored on, so they are not directly comparable.
2. **Summarize** (:func:`source_summaries`, :func:`win_table`, :func:`per_mouse_table`): paired
   differences with mean ± se and tests across mice from
   ``choice_logit_extensions.MIN_TEST_MICE`` mice, which model wins each mouse, and every
   mouse's numbers and fitted parameters.
3. **Recover** (:func:`recover_models`): can this comparison tell the models apart at these
   trial counts? Each mouse's fitted WSLS (Magnitude), Heuristic+ and Q-learner are played on
   that mouse's own problems (same ports, initiation port, starting magnitudes and numbers of
   sessions and trials; the magnitudes then follow the task's rules), and every simulated mouse
   goes through the same comparison. The result is the confusion matrix (which model wins for
   data generated by each model) and how well the parameters come back.

Drawing is in :mod:`src.behavior_visualization.plot_strategy_models`.
"""

