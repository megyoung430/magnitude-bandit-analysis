def simulate_model_trials(
    trials: pd.DataFrame, params, model: str, rules: sim.TaskRules, seed: int
) -> pd.DataFrame:
    """One simulated mouse: *model* with *params* playing the problems of one mouse's *trials*.

    The simulated mouse keeps the real mouse's id, problems, ports, initiation ports, starting
    magnitudes and numbers of sessions and trials; the magnitudes follow *rules*.

    Args:
        trials (pd.DataFrame): The real mouse's drifting trial table.
        params: Parameters of *model* (``strategy_models.SPECS``).
        model (str): One of ``strategy_models.MODELS``.
        rules (sim.TaskRules): Drift and block lengths of the simulated task.
        seed (int): Seed of this simulation; with the mouse and the model it sets the stream.

    Returns:
        pd.DataFrame: The simulated drifting trial table.
    """
    mouse = trials["mouse"].iloc[0]
    rng = np.random.default_rng([seed, zlib.crc32(str(mouse).encode()), sm.MODELS.index(model)])
    played = sim.simulate_policy_mouse(
        lambda layout: sm.SPECS[model].policy(params, layout),
        sim.mouse_layouts(trials),
        rules,
        rng,
        mouse,
    )
    return drifting_trial_table(played)


class _MouseRecovery(NamedTuple):
    won: pd.DataFrame
    nats: pd.DataFrame
    parameters: pd.DataFrame
    failed: pd.DataFrame


def recover_mouse(
    trials: pd.DataFrame,
    fits: Mapping[str, object],
    rules: sim.TaskRules,
    replicates: int,
    seed: int,
    n_starts: int,
    version: str,
) -> _MouseRecovery:
    """Simulate one mouse with each model and compare all models on the simulated mice.

    Args:
        trials (pd.DataFrame): The mouse's drifting trial table (the problems to play).
        fits (Mapping[str, object]): ``{model: params}`` fitted to the mouse.
        rules (sim.TaskRules): Drift and block lengths of the simulated task.
        replicates (int): Simulated mice per model.
        seed (int): Base seed.
        n_starts (int): Random starts of each Q-learner fit.
        version (str): ``code_version()``; only part of the cache key.

    Returns:
        _MouseRecovery: ``mouse, generator, replicate, winner``; the held-out nats of every
        model; the generating and recovered parameters of the generating model; and the
        simulated mice that could not be compared (with the reason).
    """
    mouse = trials["mouse"].iloc[0]
    won, nats, parameters, failed = [], [], [], []
    for generator in sm.MODELS:
        true = sm.parameters_table(mouse, {generator: fits[generator]})
        for replicate in range(replicates):
            simulated = simulate_model_trials(
                trials, fits[generator], generator, rules, seed * 100_000 + replicate
            )
            key = dict(mouse=mouse, generator=generator, replicate=replicate)
            if reason := sm.skip_reason(simulated, min_trials=0):
                failed.append({**key, "reason": reason})
                continue
            result = sm.cross_validate(simulated, n_starts, seed)
            table = sm.nats_table(result.scores)
            won.append({**key, "winner": sm.winners(table)["winner"].iloc[0]})
            nats.append(table.assign(**key))
            fitted = result.parameters[result.parameters["model"] == generator]
            parameters.append(sm.parameter_recovery_table(true, fitted).assign(**key))
    return _MouseRecovery(
        won=pd.DataFrame(won, columns=["mouse", "generator", "replicate", "winner"]),
        nats=pd.concat(nats, ignore_index=True) if nats else pd.DataFrame(),
        parameters=pd.concat(parameters, ignore_index=True) if parameters else pd.DataFrame(),
        failed=pd.DataFrame(failed, columns=["mouse", "generator", "replicate", "reason"]),
    )


def mouse_recoverer(cache_dir: Path | None):
    """:func:`recover_mouse`, cached under *cache_dir* if one is given."""
    return recover_mouse if cache_dir is None else Memory(cache_dir, verbose=0).cache(recover_mouse)


class Recovery(NamedTuple):
    """Model and parameter recovery on simulated mice.

    Attributes:
        won (pd.DataFrame): ``mouse, generator, replicate, winner`` of every simulated mouse.
        nats (pd.DataFrame): Held-out nats per choice of every model on every simulated mouse.
        counts (pd.DataFrame): ``strategy_models.recovery_matrix`` counts (generating model in
            rows, winning model in columns).
        fractions (pd.DataFrame): The same as fractions of each row.
        parameters (pd.DataFrame): Generating against recovered parameters of the generating
            model, ``mouse, generator, replicate, parameter, true, estimate, error``.
        summary (pd.DataFrame): ``generator`` and ``strategy_models.parameter_recovery_summary``.
        failed (pd.DataFrame): Simulated mice that could not be compared, with the reason.
        replicates (int): Simulated mice per mouse and model.
        seed (int): Base seed.
        n_starts (int): Random starts of each Q-learner fit.
    """

    won: pd.DataFrame
    nats: pd.DataFrame
    counts: pd.DataFrame
    fractions: pd.DataFrame
    parameters: pd.DataFrame
    summary: pd.DataFrame
    failed: pd.DataFrame
    replicates: int
    seed: int
    n_starts: int


def recover_models(
    trial_table: pd.DataFrame,
    source: SourceComparison,
    *,
    rules: sim.TaskRules | Mapping | None = None,
    replicates: int = 1,
    seed: int = RECOVERY_SEED,
    n_starts: int | None = None,
    n_jobs: int = 1,
    cache_dir: Path | None = None,
) -> Recovery:
    """Play every model of every mouse of *source* on that mouse's problems and compare them.

    Args:
        trial_table (pd.DataFrame): The trial table *source* was compared from.
        source (SourceComparison): From :func:`analyze_comparison_source`; its fits are the
            generating parameters.
        rules (sim.TaskRules | Mapping | None): The simulated task, one rule set or
            ``{cohort: rules}``. Default ``None``: measured within each cohort of *trial_table*.
        replicates (int): Simulated mice per mouse and model. Default 1.
        seed (int): Base seed. Default ``RECOVERY_SEED``.
        n_starts (int | None): Random starts of each Q-learner fit. Default ``None``: those of
            *source*.
        n_jobs (int): Parallel workers over mice. Default 1.
        cache_dir (Path | None): Cache each mouse's recovery here. Default ``None``.

    Returns:
        Recovery: The confusion matrix, the parameter recovery and the underlying tables.

    Raises:
        ValueError: If fewer than one replicate is asked for, or no simulated mouse could be
            compared.
        RuntimeError: If a fit does not converge or runs to a bound.

    Warns:
        UserWarning: For simulated mice that could not be compared.
    """
    if replicates < 1:
        raise ValueError(f"replicates must be at least 1, got {replicates}")
    n_starts = source.n_starts if n_starts is None else n_starts
    mice = sorted(source.fits)
    rules_of = switch_pipe.rules_by_mouse(trial_table, mice, rules)
    by_mouse = {m: rows.reset_index(drop=True) for m, rows in trial_table.groupby("mouse")}
    recover, version = mouse_recoverer(cache_dir), code_version()
    results = Parallel(n_jobs=n_jobs)(
        delayed(recover)(by_mouse[m], source.fits[m], rules_of[m], replicates, seed, n_starts,
                         version)
        for m in mice
    )  # fmt: skip
    failed = pd.concat([r.failed for r in results], ignore_index=True)
    for row in failed.itertuples():
        warnings.warn(
            f"mouse {row.mouse}: simulated {row.generator} mouse {row.replicate} cannot be "
            f"compared: {row.reason}",
            stacklevel=2,
        )
    won = pd.concat([r.won for r in results], ignore_index=True)
    if won.empty:
        raise ValueError("no simulated mouse could be compared")
    counts, fractions = sm.recovery_matrix(won)
    parameters = pd.concat([r.parameters for r in results if not r.parameters.empty],
                           ignore_index=True)  # fmt: skip
    summary = pd.concat(
        [sm.parameter_recovery_summary(group).assign(generator=generator)
         for generator, group in parameters.groupby("generator", sort=False)],
        ignore_index=True,
    )  # fmt: skip
    return Recovery(
        won=won,
        nats=pd.concat([r.nats for r in results if not r.nats.empty], ignore_index=True),
        counts=counts,
        fractions=fractions,
        parameters=parameters,
        summary=summary[["generator", *[c for c in summary.columns if c != "generator"]]],
        failed=failed,
        replicates=replicates,
        seed=seed,
        n_starts=n_starts,
    )
